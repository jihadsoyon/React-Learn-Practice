// Fake API
export const fetchJobs = (filters = {}, page = 1, limit = 6) => {
  return new Promise((resolve) => {
    setTimeout(() => {
      let results = [...fakeJobs];

      if (filters.query) {
        const q = filters.query.toLowerCase();
        results = results.filter(
          (j) =>
            j.title.toLowerCase().includes(q) ||
            j.company.toLowerCase().includes(q) ||
            j.tags.some((t) => t.toLowerCase().includes(q))
        );
      }
      if (filters.category && filters.category !== "All") {
        results = results.filter((j) => j.category === filters.category);
      }
      if (filters.location && filters.location !== "All") {
        results = results.filter((j) => j.location === filters.location);
      }
      if (filters.type && filters.type !== "All") {
        results = results.filter((j) => j.type === filters.type);
      }
      if (filters.salary && filters.salary.label !== "Any") {
        results = results.filter(
          (j) => j.salary.max >= filters.salary.min && j.salary.min <= filters.salary.max
        );
      }

      const total = results.length;
      const start = (page - 1) * limit;
      const paginated = results.slice(start, start + limit);

      resolve({ jobs: paginated, total, pages: Math.ceil(total / limit) });
    }, 800);
  });
};